// Stale cleanup (task 2.1)
// ==========================================================================

test("hubs removes a stale hub note but preserves a non-hub note", (t) => {
  const root = mkRoot();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  seedFoo(root);
  // A leftover hub note whose change dir is gone (e.g. archived).
  writeFile(root, "openspec/changes/archive/2026-01-01-gone/proposal.md", "---\n---\n");
  writeFile(
    root,
    "openspec/changes/gone.md",
    '---\ntype: hub\nchange: gone\n---\n\n# gone\n',
  );
  // A user's own note that is NOT a hub — must never be touched.
  const userNote = "---\ntype: note\n---\n\n# my notes\n";
  writeFile(root, "openspec/changes/notes.md", userNote);

  const r = hubs(root);
  assert.deepEqual(r.written, ["changes/add-foo.md"]);
  assert.deepEqual(r.removed, ["changes/gone.md"]);
  assert.equal(fs.existsSync(path.join(root, "openspec/changes/gone.md")), false, "stale hub gone");
  assert.equal(readFile(root, "openspec/changes/notes.md"), userNote, "non-hub note preserved");
  assert.ok(fs.existsSync(path.join(root, "openspec/changes/add-foo.md")), "active hub written");
});

test("hubs --dry-run previews writes and removals without touching the vault", (t) => {
  const root = mkRoot();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  seedFoo(root);
  writeFile(root, "openspec/changes/gone.md", "---\ntype: hub\nchange: gone\n---\n");

  const before = fs.readdirSync(path.join(root, "openspec/changes")).sort();
  const goneBytes = readFile(root, "openspec/changes/gone.md");

  const r = hubs(root, { dryRun: true });
  assert.deepEqual(r.written, ["changes/add-foo.md"]);
  assert.deepEqual(r.removed, ["changes/gone.md"]);

  const after = fs.readdirSync(path.join(root, "openspec/changes")).sort();
  assert.deepEqual(after, before, "no files created or deleted");
  assert.equal(fs.existsSync(path.join(root, "openspec/changes/add-foo.md")), false, "nothing written");
  assert.equal(readFile(root, "openspec/changes/gone.md"), goneBytes, "stale hub untouched");
});

test("hubs is a no-op with no active changes", (t) => {
  const root = mkRoot();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  writeFile(root, "openspec/config.yaml", "x: 1\n");
  const r = hubs(root);
  assert.deepEqual(r, { written: [], removed: [] });
});

test("hubs throws HubsError when openspec/ is absent", () => {
  const root = mkRoot();
  assert.throws(() => hubs(root), (e) => e instanceof HubsError && /no openspec\//.test(e.message));
  fs.rmSync(root, { recursive: true, force: true });
});

// ==========================================================================
// Inertness to the rest of the toolchain (task 3.2)
// ==========================================================================

test("backfill leaves a hub note byte-for-byte unchanged", (t) => {
  const root = mkRoot();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  seedFoo(root);
  hubs(root);
  const hubBytes = readFile(root, "openspec/changes/add-foo.md");

  const res = backfill(root);
  assert.ok(
    !res.written.includes("changes/add-foo.md"),
    "hub note is not treated as a backfill artifact",
  );
  assert.equal(readFile(root, "openspec/changes/add-foo.md"), hubBytes, "hub note unchanged");
});

test("dashboard discovery is identical with and without hub notes present", (t) => {
  const root = mkRoot();
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  seedFoo(root);

  const before = renderDashboard({ ...collectChanges(root), specs: [] });
  hubs(root); // materialize hub notes beside the change dirs
  const after = renderDashboard({ ...collectChanges(root), specs: [] });

  assert.equal(after, before, "hub notes do not alter dashboard output");
});
